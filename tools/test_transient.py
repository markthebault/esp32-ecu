 def test_zero_decel_stops_executed_injector_starts_on_both_dispatchers(self):
  for cls in (EngineRuntime,TargetRuntime):
   for strategy in ('batch_wasted_4cyl','semi_sequential_4cyl'):
    t=tune();t['strategy']=strategy;t['transient_enrichment'].update(duration_ms=150,decel_fuel_pct=0)
    r=cls(t);r.wheel();edges=[];observations=[];sample=0;index=0
    teeth=[200000+round((rev*60+slot)*50000/60) for rev in range(16) for slot in range(58)]
    try:
     while True:
      now=min(sample,teeth[index] if index<len(teeth) else 2**64-1,r.next_event_us())
      if now>900000:break
      while r.next_event_us()<=now:
       due=r.next_event_us();event=r.pop_event()
       if event is None:raise AssertionError('Missing scheduled event')
       if event[0]==-1:continue
       if event[0] is None:r.cut()
       else:edges.append((due,event[0],event[1]))
      if index<len(teeth) and teeth[index]==now:
       if r.trigger(now) in (2,3):r.cut()
       index+=1
      if sample==now:
       acquired=now//5000*5000
       tps=10 if acquired<400000 or acquired>=540000 else (min(18,10+(acquired-400000)/5000) if acquired<500000 else 18-(acquired-500000)/5000)
       out=r.step(dict(tps_pct=tps),now,acquired)
       observations.append((now,out))
       if out['faults'] or out['state']=='stopped':r.cut()
       sample+=1000
     cut=[time for time,o in observations if o['transient_enrichment']['phase_code']==2]
     self.assertTrue(cut);self.assertTrue(all(o['fuel_cut'] and not o['spark_cut'] and o['pulse_ms']==0 for _,o in observations if o['transient_enrichment']['phase_code']==2))
     first,last=min(cut),max(cut)
     # Scheduler observes the cut at the next accepted crank plan. Permit one
     # regular tooth plus quantization; active closing edges finish normally.
     self.assertFalse(any(high and ch<4 and first+1000<=time<=last for time,ch,high in edges))
     self.assertTrue(any(not high and ch>=4 and first+1000<=time<=last for time,ch,high in edges))
     self.assertTrue(any(high and ch<4 and last+5000<time<850000 for time,ch,high in edges))
     high={};maximum=[0]*8
     for time,ch,value in edges:
      if value:self.assertNotIn(ch,high);high[ch]=time
      else:self.assertIn(ch,high);maximum[ch]=max(maximum[ch],time-high.pop(ch))
     self.assertLessEqual(max(maximum[:4]),15000);self.assertLessEqual(max(maximum[4:]),3500)
     self.assertFalse(out['physical_outputs_enabled']);self.assertEqual(out['faults'],0)
    finally:r.close()

 def test_legacy_outputs_match_independent_committed_source_oracle(self):
  # Generated by the independent reviewer from immutable64c21ed engine.hpp,
  # before this implementation. Extra observations never redefine the oracle.
  rows=list(csv.DictReader(io.StringIO((R/'config/engine/fixtures/transient-legacy-v5.csv').read_text())));runtime=None;case=None
  try:
   for row in rows:
    if row['case']!=case:
     if runtime:runtime.close()
     old=json.loads((R/'config/engine/defaults-v5.json').read_text());case=row['case']
     if case=='ego_gating':old['settings'].update(ego_enabled=True,afterstart_pct=0)
     runtime=EngineRuntime(old);self.assertEqual(runtime.tune['transient_enrichment']['mode'],'legacy_tps')
    out=runtime.step(dict(rpm=float(row['rpm']),tps_pct=float(row['tps']),map_kpa=45,clt_c=85,iat_c=25,battery_v=14,sensor_v=5,lambda_ready=True,synced=True),int(row['control_us']),int(row['sampled_us']),use_decoder=False)
    for key in ('accel','ego','pulse_ms'):self.assertAlmostEqual(out[key],float(row[key]),delta=1e-12)
    self.assertEqual(out['faults'],int(row['faults']));self.assertEqual(out['fuel_cut'],bool(int(row['fuel_cut'])));self.assertEqual(runtime.data()['state_code'],int(row['state']))
  finally:
   if runtime:runtime.close()

 def test_sensor_acquisition_window_is_independent_of_control_age(self):
  a=EngineRuntime(tune());b=EngineRuntime(tune())
  try:
   immediate=ramp(a);delayed=ramp(b,15000)
   self.assertEqual(immediate['transient_enrichment']['tps_dot_pct_s'],100)
   self.assertEqual(delayed['transient_enrichment']['tps_dot_pct_s'],100)
   self.assertEqual(immediate['transient_enrichment']['remaining_ms'],200)
   self.assertEqual(delayed['transient_enrichment']['remaining_ms'],185)
   self.assertAlmostEqual(immediate['pulse_ms'],delayed['pulse_ms'])
   repeated=b.step(dict(rpm=1000,map_kpa=50,tps_pct=80,synced=True),40000,20000,use_decoder=False)
   self.assertEqual(repeated['transient_enrichment']['tps_dot_pct_s'],100)
   self.assertEqual(repeated['transient_enrichment']['remaining_ms'],180)
  finally:a.close();b.close()


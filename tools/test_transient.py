def tune(mode='tps_rate'):
 t=json.loads((R/'config/engine/defaults.json').read_text());t['settings']['afterstart_pct']=0;t['settings']['dfco_enabled']=False
 t['transient_enrichment'].update(mode=mode,tps_min_change_pct=0,map_min_change_kpa=0)
 return t

def ramp(runtime,delay=0,apply='multiply'):
 result=None
 for n in range(5):
  stamp=n*5000;result=runtime.step(dict(rpm=1000,map_kpa=50,tps_pct=10+n*.5,synced=True),stamp+delay,stamp,use_decoder=False)
 return result


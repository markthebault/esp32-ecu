#!/usr/bin/env python3
"""Independent unequal-cylinder plant and unchanged Speeduino production control.

Physics constants below are not generated by either ECU. Trim settings are an
explicit attempted calibration, including an intentionally wrong-cylinder case.
"""
import argparse,copy,hashlib,json,math,statistics,time
from pathlib import Path
import compare_engine_controllers as benchmark
from engine_research_plant import ResearchPlant
from run_target_scenarios import TargetController
from speeduino_runtime import SpeeduinoRuntime

R=Path(__file__).resolve().parents[1]
FLOW=(1.,.9,1.08,.95);SPARK=(-3,2,5,-4)

def trims(mode,base_pw_us=None):
 t=benchmark.benchmark_tune()['cylinder_trims'];t['enabled']=mode!='disabled'
 if mode in ('disabled','corrected','swapped'):
  for i in range(4):t['fuel_maps'][i]['cells']=[100/FLOW[i]]*36
  t['spark_deg']=list(SPARK)
 if mode=='swapped':
  t['fuel_maps'][1],t['fuel_maps'][2]=t['fuel_maps'][2],t['fuel_maps'][1]
  t['spark_deg'][1],t['spark_deg'][2]=t['spark_deg'][2],t['spark_deg'][1]
 if mode=='total_pw_adjusted':
  if base_pw_us is None or base_pw_us<=900:raise ValueError('Measured neutral reference PW must exceed fixed benchmark deadtime')
  for i in range(4):t['fuel_maps'][i]['cells']=[100*(900+(base_pw_us-900)/FLOW[i])/base_pw_us]*36
  t['spark_deg']=list(SPARK)
 return t

def metrics(plant):
 rows=[]
 for cylinder in range(1,5):
  burns=[r for r in plant.cylinder_combustions if r['cylinder']==cylinder and r['time_s']>=8 and r['lambda_value'] is not None]
  mean=lambda key:statistics.mean(r[key] for r in burns) if burns else None
  rows.append(dict(cylinder=cylinder,attempts=len(burns),burns=sum(r['scheduled_work_j']>0 for r in burns),mean_lambda=mean('lambda_value'),
    mean_charge_fuel_mg=mean('fuel_mg'),mean_air_mg=mean('air_mg'),
    mean_advance_deg=mean('advance_deg'),mean_scheduled_work_j=mean('scheduled_work_j'),
    total_delivered_fuel_mg=plant.cylinder_fuel_mg[cylinder-1],total_shaft_j=plant.cylinder_shaft_j[cylinder-1]))
 values=[r['mean_lambda'] for r in rows];work=[r['mean_scheduled_work_j'] for r in rows]
 complete=all(r['burns'] and r['burns']==r['attempts'] for r in rows)
 return dict(cylinders=rows,complete=complete,lambda_spread=max(values)-min(values) if complete else None,
             lambda_cv=statistics.pstdev(values)/statistics.mean(values) if complete else None,
             work_cv=statistics.pstdev(work)/statistics.mean(work) if complete else None,
             shaft_sum_j=sum(plant.cylinder_shaft_j),shaft_total_j=plant.combustion_shaft_j)

def validate(output):
 output.mkdir(parents=True,exist_ok=True);original=(benchmark.OurController,benchmark.SpeeduinoRuntime,benchmark.ResearchPlant);rows=[];failures=[];started=time.monotonic()
 digest=lambda path:hashlib.sha256(Path(path).read_bytes()).hexdigest()
 try:
  for who in ('ours','speeduino'):
   base_pw=None
   for mode in ('disabled','neutral','corrected','swapped')+ (('total_pw_adjusted',) if who=='speeduino' else ()):
    active=trims(mode,base_pw);plants=[];attest=[]
    class FixedUnequalPlant(ResearchPlant):
     def __init__(self):super().__init__(injector_flow_factors=FLOW,optimum_spark_offsets=SPARK);plants.append(self)
    class Project(TargetController):
     def __init__(self,tune=None):
      t=copy.deepcopy(tune or benchmark.benchmark_tune());t['cylinder_trims']=copy.deepcopy(active);super().__init__(t)
    class Reference(SpeeduinoRuntime):
     def __init__(self,**kwargs):
      super().__init__(**kwargs);self.cylinder_trims(active)
      manifest=R/'.cache/engine/speeduino-sim16/build-manifest.json';binary=digest(Path('/proc')/str(self.process.pid)/'exe')
      if json.loads(manifest.read_text())['binary_sha256']!=binary:raise RuntimeError('Running reference differs from build manifest')
      attest.append(dict(live_executable_sha256=binary,manifest_sha256=digest(manifest)))
    benchmark.OurController=Project;benchmark.SpeeduinoRuntime=Reference;benchmark.ResearchPlant=FixedUnequalPlant
    print('Running',who,mode,flush=True)
    result=benchmark.run(who,'warm_start',10,250,control_period_us=5000,sequential=True,reference_timer_bits=16)
    m=metrics(plants[0]);summary=result['summary']
    if mode=='disabled' and who=='speeduino':base_pw=result['trace'][-1]['ecu']['pulse_us']
    if not summary['mean_final_second_rpm']>500 or summary['final_outputs_high'] or summary['max_dwell_high_us']>3504:failures.append([who,mode,'sustained run/output bounds'])
    if not m['complete']:failures.append([who,mode,'missing final-window cylinder combustion'])
    if summary['wrong_stroke_sparks'] or summary['unsynced_720_discharges']:failures.append([who,mode,'wrong-stroke or unsynced discharge'])
    if abs(m['shaft_sum_j']-m['shaft_total_j'])>1e-6:failures.append([who,mode,'per-cylinder shaft ledger'])
    record=dict(controller=who,mode=mode,physics=dict(injector_flow_factors=FLOW,optimum_spark_offsets=SPARK),trim_tune=active,metrics=m,summary=summary)
    if attest:record['reference_attestation']=attest[0]
    if mode=='total_pw_adjusted':record['calibration']=dict(neutral_pw_us=base_pw,fixed_deadtime_us=900,formula='100*(deadtime+(neutral_pw-deadtime)/flow_factor)/neutral_pw',scope='Single steady operating point, then reference integer-percent quantization; not a full engine calibration')
    (output/f'{who}-{mode}.json').write_text(json.dumps(dict(**record,combustions=plants[0].cylinder_combustions,edges=result['edges'],trace=result['trace'],spark_timing=result['spark_timing']),separators=(',',':'))+'\n')
    rows.append(record);print('lambda spread',m['lambda_spread'],'workCV',m['work_cv'],flush=True)
  for who in ('ours','speeduino'):
   cases={r['mode']:r for r in rows if r['controller']==who};baseline=cases['disabled']['metrics'];corrected=cases['corrected']['metrics'];wrong=cases['swapped']['metrics']
   if not all(m['complete'] for m in (baseline,corrected,wrong)):continue
   # Inverse flow compensates effective fuel exactly in our policy. The same
   # numbers overcorrect Speeduino's total PW, especially at short pulses.
   # Keep that declared difference, then test its own deadtime-aware setting.
   limit=.25 if who=='ours' else .5
   if not corrected['lambda_spread']<baseline['lambda_spread']*limit:failures.append([who,'corrected','fuel balancing absent'])
   if not corrected['work_cv']<baseline['work_cv']*.5:failures.append([who,'corrected','work balancing absent'])
   if not wrong['lambda_spread']>max(corrected['lambda_spread']*3,baseline['lambda_spread']*1.5):failures.append([who,'swapped','negative control did not detect mapping error'])
   if who=='speeduino':
    adjusted=cases['total_pw_adjusted']['metrics']
    if not adjusted['complete'] or not adjusted['lambda_spread']<baseline['lambda_spread']*.1:failures.append([who,'total_pw_adjusted','policy-aware calibration did not balance fuel'])
  files=['tools/run_cylinder_scenarios.py','tools/engine_research_plant.py','tools/speeduino_runtime.py','tools/speeduino_sim.cpp','tools/target_timing_bridge.cpp','tools/compare_engine_controllers.py','config/engine/defaults.json','firmware/include/ecu/engine.hpp','firmware/include/ecu/engine_scheduler.hpp','firmware/include/ecu/timing_executor.hpp']
  files+=['tools/run_target_scenarios.py','tools/target_runtime.py','tools/speeduino_sim_hal.cpp','tools/speeduino_sim_native.hpp','simulation/modelica/EngineAirPath.mo']
  files+=sorted(str(p.relative_to(R)) for p in (R/'firmware/include/ecu').glob('*.hpp'))
  report=dict(scope='Independent unequal-cylinder empirical combustion/free-shaft with hash-verified external MVEM air path; native target core and unmodified pinned Speeduino production algorithms on separate plant instances; no physical qualification',
    reference='Native Mega-like16-bit/4us timer HAL, zero CPU/IRQ execution cost; fuel trims quantized to integer delta percent and native ascending RPM/100,load/2 axes',
    intentional_difference='Project trims effective fuel before fixed deadtime; Speeduino applies percentageApprox to whole primary PW. Spark limits and cam-loss policy also differ explicitly.',
    rows=rows,failures=failures,passed=not failures,runtime_seconds=time.monotonic()-started,source_hashes={name:digest(R/name) for name in files},
    runtime_artifacts={name:digest(R/name) for name in ['.cache/engine/target-native/libtarget_engine.so','.cache/engine/modelica-mvem/airpath/EngineAirPath.fmu','.cache/engine/modelica-mvem/airpath/manifest.json']})
  (output/'summary.json').write_text(json.dumps(report,indent=2)+'\n');return report
 finally:benchmark.OurController,benchmark.SpeeduinoRuntime,benchmark.ResearchPlant=original

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--report-dir',type=Path,default=R/'.cache/engine/cylinder-scenarios');a=p.parse_args();r=validate(a.report_dir);print(json.dumps(dict(passed=r['passed'],failures=r['failures']),indent=2));raise SystemExit(0 if r['passed'] else 1)

#!/usr/bin/env python3
"""Generate the current source/basis UI contract from own008 metadata."""
import json,sys
from pathlib import Path
R=Path(__file__).resolve().parents[1];sys.path.insert(0,str(R/'tools'))
from load_config import DEFAULT,ENUM_FIELDS,SCALARS,ENUMS,LABELS,UNITS,LIMITS,VALUE_NAMES,AFR_STATES
metadata=dict(defaults=DEFAULT,enums=ENUMS,labels=LABELS,enumFields=ENUM_FIELDS,scalars=SCALARS,units=UNITS,limits=LIMITS,values=VALUE_NAMES,afrStates=AFR_STATES)
(R/'web/load_model.js').write_text('// Generated by scripts/generate_load_ui.py\nwindow.EcuLoadMetadata='+json.dumps(metadata,separators=(',',':'))+';\n'+(R/'web/load_model_logic.js').read_text())

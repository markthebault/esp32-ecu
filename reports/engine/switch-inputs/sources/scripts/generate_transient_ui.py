#!/usr/bin/env python3
"""Generate current transient UI metadata from the stable own007 layout."""
import json,sys
from pathlib import Path
R=Path(__file__).resolve().parents[1];sys.path.insert(0,str(R/'tools'))
from transient_config import DEFAULT,MODES,MODE_LABELS,APPLIES,APPLY_LABELS,SCALARS,ARRAYS,UNITS,LIMITS
metadata=dict(defaults=DEFAULT,modes=MODES,modeLabels=MODE_LABELS,applies=APPLIES,applyLabels=APPLY_LABELS,scalars=SCALARS,arrays=ARRAYS,units=UNITS,limits=LIMITS)
(R/'web/transient_enrichment.js').write_text('// Generated by scripts/generate_transient_ui.py\nwindow.EcuTransientMetadata='+json.dumps(metadata,separators=(',',':'))+';\n'+(R/'web/transient_enrichment_logic.js').read_text())

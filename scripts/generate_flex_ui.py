#!/usr/bin/env python3
"""Generate flex browser metadata from the calibration/wire contract."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'tools'))
import flex_config as f
metadata=dict(defaults=f.DEFAULT,captureFloats=f.CAPTURE_FLOATS,arrays=f.ARRAYS,booleans=f.BOOLEANS,limits=f.LIMITS,labels=f.LABELS,units=f.UNITS,values=f.VALUES,flags=f.FLAGS,codes=f.CODES,times=f.TIMES,sources=f.SOURCE_NAMES,reasons=f.REASONS,logFields=f.log_fields())
(ROOT/'web/flex_fuel.js').write_text('// Generated by scripts/generate_flex_ui.py\nwindow.EcuFlexMetadata='+json.dumps(metadata,separators=(',',':'))+';\n'+(ROOT/'web/flex_fuel_logic.js').read_text())

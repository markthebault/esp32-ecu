#!/usr/bin/env python3
"""Generate boost browser metadata from the shared calibration layout."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'tools'))
import boost_config as b
metadata=dict(defaults=b.DEFAULT,scalars=b.SCALARS,tables=b.TABLES,modes=b.MODES,activations=b.ACTIVATIONS,limits=b.LIMITS,units=b.UNITS,labels=b.LABELS,values=b.VALUES,reasons=b.REASONS)
(ROOT/'web/boost_control.js').write_text('// Generated by scripts/generate_boost_ui.py\nwindow.EcuBoostMetadata='+json.dumps(metadata,separators=(',',':'))+';\n'+(ROOT/'web/boost_control_logic.js').read_text())
